test('revision-health receipt uses v2 schema', () => {
  expect(DEFAULT_BRANCH_REVISION_HEALTH_RECEIPT.schema).toBe(
    REVISION_HEALTH_RECEIPT_SCHEMA
  );
  expect(DEFAULT_BRANCH_REVISION_HEALTH_RECEIPT.schema).toBe(
    'sec-default-branch-revision-health-receipt-v2'
  );
});

test('revision-health receipt is bound to exact subject revision b2e538ae', () => {
  expect(DEFAULT_BRANCH_REVISION_HEALTH_RECEIPT.defaultBranch).toBe('main');
  expect(DEFAULT_BRANCH_REVISION_HEALTH_RECEIPT.subjectRevision).toBe(SUBJECT_REVISION);
});

test('revision-health receipt does not authorize any revision other than the subject', () => {
  // The b2e538ae receipt must NOT be reusable for b1220ae3 or any other revision.
  // Each revision requires its own receipt generated by its own executor invocation.
  expect(DEFAULT_BRANCH_REVISION_HEALTH_RECEIPT.subjectRevision).not.toBe(
    'b1220ae333679ac6bf4a181b0242a31ad3d6975f'
  );
  // Every gate's subjectRevision must match the receipt's subjectRevision.
  for (const gate of DEFAULT_BRANCH_REVISION_HEALTH_RECEIPT.gates) {
    expect(gate.subjectRevision).toBe(SUBJECT_REVISION);
  }
});

