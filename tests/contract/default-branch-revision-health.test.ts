test('revision-health receipt has no self-declared trustEligibility or verificationHealth', () => {
  // Trust cannot be self-declared. It is derived from the lattice.
  // The receipt must NOT contain these v1 fields.
  const receiptKeys = Object.keys(
    DEFAULT_BRANCH_REVISION_HEALTH_RECEIPT as unknown as Record<string, unknown>
  );
  expect(receiptKeys).not.toContain('trustEligibility');
  expect(receiptKeys).not.toContain('verificationHealth');
  expect(receiptKeys).not.toContain('postMergeVerification');
});

test('revision-health receipt has no preExistingImportsCheckFailures or repositoryAuditFinding', () => {
  // imports:check failures are NOT labeled "non-blocking" or "pre-existing".
  // They are recorded as gate results with status='failed' in the lattice.
  const receiptKeys = Object.keys(
    DEFAULT_BRANCH_REVISION_HEALTH_RECEIPT as unknown as Record<string, unknown>
  );
  expect(receiptKeys).not.toContain('preExistingImportsCheckFailures');
  // The false-positive audit finding was removed from the audit contract.
  expect(receiptKeys).not.toContain('repositoryAuditFinding');
});

