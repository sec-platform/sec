test('executor produces a receipt with the same structure as the frozen projection', () => {
  // This test validates that the frozen projection is the output of the
  // executor function — not a hand-filled object. We re-project with the
  // same inputs and validate structural equality (ignoring timestamps
  // which are real UTC and therefore non-deterministic).
  const projectedAt = '2026-01-01T00:00:00.000Z';
  const env: VerificationGateEnvironmentV1 = {
    runtime: 'bun-test',
    os: 'test-os',
    arch: 'test-arch',
    filesystem: null,
    capabilities: [],
    toolchainRevision: 'sec-default-branch-revision-health-v2',
    providerRevisions: []
  };
  const receipt = projectDefaultBranchRevisionHealth(
    'test-revision',
    [],
    DEFAULT_BRANCH_REVISION_HEALTH_RECEIPT.provenance,
    projectedAt,
    env
  );
  expect(receipt.schema).toBe(REVISION_HEALTH_RECEIPT_SCHEMA);
  expect(receipt.subjectRevision).toBe('test-revision');
  expect(receipt.recordedAt).toBe(projectedAt);
  expect(receipt.producerIdentity).toBe('test-os-test-arch');
  // Empty gate facts → each required gate has no observations → not-run.
  expect(receipt.aggregate.overallStatus).toBe('not-run');
});

