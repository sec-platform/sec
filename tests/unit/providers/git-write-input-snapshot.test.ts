import { test } from 'bun:test';
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import path from 'node:path';
import {
  canonicalCommitTreeInput, captureGitDevelopmentCommitContract,
  compileGitDevelopmentCommitContractDigest
} from '../../../src/adapters/providers/git-read/runtime/commit-contract.ts';
import { captureGitScratchIndexDelta } from '../../../src/adapters/providers/git-read/runtime/scratch-input.ts';

const tree = 'a'.repeat(40), parent = 'b'.repeat(40), target = 'c'.repeat(40);
const person = () => ({ name: 'Maintainer', email: 'maintainer@example.test', date: '0 +0000' });
const commit = () => ({ tree, parents: [parent], message: 'Commit message', author: person(), committer: person(),
  repositoryRoot: path.resolve('repository'), worktreeRoot: path.resolve('repository'),
  ref: 'refs/heads/feature', expectedOld: parent, target, signing: 'disabled' as const, hooks: 'disabled' as const,
  preflightReceiptDigest: `sha256:${'d'.repeat(64)}` as const });

// Expected grammar and values below are declared independently of the capture
// functions. These tests do not issue a Git capability or assert an actual write.
test('commit digest preserves the prior canonical JSON domain for ordinary values', () => {
  const input = commit();
  // This explicit already-key-sorted vector is not generated by the production
  // canonicalizer or by enumerating the candidate schema.
  const expected = JSON.stringify({ author: { date: '0 +0000', email: 'maintainer@example.test', name: 'Maintainer' },
    committer: { date: '0 +0000', email: 'maintainer@example.test', name: 'Maintainer' }, expectedOld: parent,
    hooks: 'disabled', message: 'Commit message', parents: [parent], preflightReceiptDigest: `sha256:${'d'.repeat(64)}`,
    ref: 'refs/heads/feature', repositoryRoot: input.repositoryRoot, schema: 'sec-development-commit-git-contract-v1',
    signing: 'disabled', target, tree, worktreeRoot: input.worktreeRoot });
  assert.equal(compileGitDevelopmentCommitContractDigest(input), `sha256:${createHash('sha256').update(expected).digest('hex')}`);
});

test('commit policy preserves exact branch targets and rejects noncanonical identities, roots and bindings', () => {
  for (const name of ['feature', 'Feature/v2.0', 'feature/_private', 'feature/a-b', 'feature/lock', 'feature/a.locked']) {
    const value = { ...commit(), ref: `refs/heads/${name}` };
    assert.deepEqual(captureGitDevelopmentCommitContract(value), value);
  }
  for (const change of [{ signing: 'enabled' }, { hooks: 'enabled' }, { expectedOld: target }, { tree: 'a'.repeat(41) },
    { parents: [] }, { parents: [parent, target] }, { ref: 'HEAD' }, { repositoryRoot: './relative' },
    { target: target.toUpperCase() }, { preflightReceiptDigest: 'unknown' },
    { preflightReceiptDigest: `blake3:${'d'.repeat(64)}` }, { message: 'a\0b' },
    ...['feature..old', 'feature/', 'feature//part', 'feature.', 'feature.lock',
      'feature.lock/part', 'feature/.hidden', 'feature/.', 'feature/..',
      'feature/part.lock', 'feature/part.lock/next'].map(name => ({ ref: `refs/heads/${name}` })),
    ...['refs/tags/v1', 'refs/heads/-feature', 'refs/heads/中文'].map(ref => ({ ref })),
    { repositoryRoot: path.resolve('repo\0other') }, { worktreeRoot: path.resolve('repo\0other') }]) {
    assert.equal(captureGitDevelopmentCommitContract({ ...commit(), ...change } as never), null);
  }
  assert.throws(() => compileGitDevelopmentCommitContractDigest({ ...commit(), ref: 'refs/heads/feature..old' }), /not canonical/);
  for (const date of ['-1 +0000', '00 +0000', '0 +1460', '0 +1401', '0 +0060', '0 +1500']) {
    assert.equal(canonicalCommitTreeInput({ ...commit(), author: { ...person(), date } }), null);
  }
  for (const date of ['0 +1400', '1 -1400', '1 +0059']) {
    assert.equal(canonicalCommitTreeInput({ ...commit(), author: { ...person(), date } })?.author.date, date);
  }
});

test('complete scratch delta capture detaches every addition before any consumer awaits', () => {
  const bytes = Uint8Array.of(0, 1, 2).subarray(1);
  const input = { additions: [{ path: 'a.ts', bytes }, { path: 'b.ts', bytes: Uint8Array.of(2) }], removals: ['old.ts'] };
  const captured = captureGitScratchIndexDelta(input, 'sha1', 1000);
  bytes.fill(9); input.additions[0]!.path = 'changed';
  input.additions[1]!.path = 'later.ts'; input.additions[1]!.bytes.fill(9); input.removals[0] = 'later.ts';
  assert.deepEqual(captured.additions.map(value => [value.path, [...value.bytes]]), [['a.ts', [1, 2]], ['b.ts', [2]]]);
  assert.deepEqual(captured.removals, ['old.ts']);
  assert.ok(Object.isFrozen(captured)); assert.ok(Object.isFrozen(captured.additions));
});

test('scratch stdin admission counts object content plus exact UTF-8 index records and removal terminators', () => {
  const input = { additions: [{ path: '好.ts', bytes: Uint8Array.of(1, 2) }], removals: ['old'] };
  for (const [format, hash] of [['sha1', 'a'.repeat(40)], ['sha256', 'a'.repeat(64)]] as const) {
    const maximum = 2 + Buffer.byteLength(`0 ${'0'.repeat(hash.length)}\told\0` + `100644 ${hash}\t好.ts\0`, 'utf8');
    assert.deepEqual(captureGitScratchIndexDelta(input, format, maximum).removals, ['old']);
    assert.throws(() => captureGitScratchIndexDelta(input, format, maximum - 1), RangeError);
  }
  assert.deepEqual(captureGitScratchIndexDelta({ additions: [], removals: [] }, 'sha1', 0), { additions: [], removals: [] });
});

test('scratch invalid paths, cross-list duplicates and array holes fail before returning a usable request', () => {
  for (const value of ['', '../a', '/a', './a', 'a/../b', 'a/./b', 'a\\b', 'a\0b']) {
    assert.throws(() => captureGitScratchIndexDelta({ additions: [], removals: [value] }, 'sha1', 1000));
  }
  assert.throws(() => captureGitScratchIndexDelta({ additions: [{ path: 'a', bytes: new Uint8Array() }], removals: ['a'] }, 'sha1', 1000));
  assert.throws(() => captureGitScratchIndexDelta({ additions: [], removals: new Array(1) }, 'sha1', 1000));
});
