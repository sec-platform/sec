/**
 * sec-default-branch-revision-health — per-revision lattice-derived receipt.
 *
 * Schema v2: the receipt is modeled per exact subject revision and its
 * verification health is computed by the required-check lattice
 * (`CodexDevelopmentAggregateVerificationClaimsV1`), not self-declared.
 *
 * Key changes from v1:
 * - `subjectRevision` binds the receipt to one exact revision (b2e538ae).
 *   The b2e538ae receipt does NOT authorize any other revision (e.g. b1220ae3).
 * - `aggregate.overallStatus` replaces the hardcoded `verificationHealth`.
 *   imports:check failed on b2e538ae → overallStatus is `failed`.
 * - No `trustEligibility` field. Trust cannot be self-declared; it is derived
 *   from the lattice (only `passed` when every required gate is `passed`).
 * - Each gate carries `VerificationGateExecutionV1` (argv, exitCode, timestamps,
 *   outputDigest, failureFingerprint) and `VerificationGateEnvironmentV1`
 *   (runtime, os, arch, toolchainRevision).
 * - `recordedAt` and gate execution timestamps are real UTC generated by the
 *   executor at projection time — not hand-filled.
 * - No "non-blocking" designation for imports:check failures. A required
 *   deterministic failure is blocking by definition (lattice → `failed`).
 * - No `repositoryAuditFinding` for `control-plane-selected-manifest-already-
 *   on-default` — that was a false positive removed from the audit contract.
 *
 * The source file is a validated projection: the receipt is the output of
 * `projectDefaultBranchRevisionHealth()` called with real environment capture
 * at module load. Tests validate the projection against the executor function,
 * not the projection against itself.
 *
 * Authority: docs/work-packages/default-branch-health-repair-v2.md
 */

