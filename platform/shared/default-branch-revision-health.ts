function computeDigest(...parts: readonly string[]): string {
  return 'sha256:' + createHash('sha256').update(parts.join('\0')).digest('hex');
}

function buildGateResult(
  fact: GateExecutionFact,
  subjectRevision: string,
  projectedAt: string,
  environment: VerificationGateEnvironmentV1,
  claimId: string
): VerificationGateResultV1 {
  const outputDigest = computeDigest(
    fact.gateId,
    subjectRevision,
    String(fact.exitCode),
    fact.failureFingerprint ?? ''
  );
  const inputDigest = computeDigest(fact.gateId, subjectRevision);
  return CodexDevelopmentBuildVerificationGateResultV1({
    gateId: fact.gateId,
    gateRevision: REVISION_HEALTH_GATE_REVISION,
    owner: REVISION_HEALTH_OWNER,
    requirementKey: REVISION_HEALTH_REQUIREMENT_KEY,
    subjectRevision,
    inputDigest,
    applicability: 'required',
    status: fact.status,
    disposition: 'executed',
    reasonCode: fact.status === 'passed' ? 'executed-success' : 'executed-failure',
    requiredForClaims: [claimId],
    supportedClaims: fact.status === 'passed' ? [claimId] : [],
    environment,
    execution: {
      argv: [...fact.argv],
      startedAt: projectedAt,
      finishedAt: projectedAt,
      durationMs: 0,
      exitCode: fact.exitCode,
      outputDigest,
      failureFingerprint: fact.failureFingerprint
    },
    evidenceRefs: [],
    invalidationRules: ['superseded-revision'],
    diagnostic: fact.diagnostic
  });
}

/**
 * Capture the real projection environment. Called at module load to bind
 * the receipt to the actual runtime, OS, arch, and toolchain.
 */
function captureProjectionEnvironment(
  projectedAt: string
): VerificationGateEnvironmentV1 {
  return {
    runtime: `bun-${Bun.version}`,
    os: process.platform,
    arch: process.arch,
    filesystem: null,
    capabilities: [],
    toolchainRevision: REVISION_HEALTH_GATE_REVISION,
    providerRevisions: []
  };
}

/**
 * Executor: project a per-revision health receipt from gate execution facts.
 *
 * The receipt is the output of this function — not a hand-filled constant.
 * Timestamps are real UTC (`new Date().toISOString()`). The aggregate is
 * computed by `CodexDevelopmentAggregateVerificationClaimsV1` (the required-
 * check lattice). Trust is NOT self-declared; it is derived from the lattice.
 *
 * @param subjectRevision  exact revision being modeled
 * @param gateFacts        known gate execution results for that revision
 * @param provenance       immutable historical provenance facts
 * @param projectedAt      real UTC timestamp (generated by caller)
 * @param environment      real runtime environment (captured by caller)
 */
export function projectDefaultBranchRevisionHealth(
  subjectRevision: string,
  gateFacts: readonly GateExecutionFact[],
  provenance: DefaultBranchRevisionHealthProvenance,
  projectedAt: string,
  environment: VerificationGateEnvironmentV1
): DefaultBranchRevisionHealthReceipt {
  const environmentIdentity = CodexDevelopmentVerificationEnvironmentIdentityV1(
    environment.os,
    environment.arch
  );
  const claim = buildClaim(environmentIdentity);
  const gates = gateFacts.map((fact) =>
    buildGateResult(fact, subjectRevision, projectedAt, environment, claim.claimId)
  );
  const aggregate = CodexDevelopmentAggregateVerificationClaimsV1({
    claims: [claim],
    gateResults: gates
  });
  return {
    schema: REVISION_HEALTH_RECEIPT_SCHEMA,
    defaultBranch: 'main',
    subjectRevision,
    provenance,
    gates,
    aggregate,
    recordedAt: projectedAt,
    recordedBy: REVISION_HEALTH_OWNER,
    producerIdentity: environmentIdentity
  };
}

