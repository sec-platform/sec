use std::collections::BTreeMap;
use crate::{Artifact, LoweredDefinition, OrderedPlan, Primitive, Program, SourceMapping, Term, TermKind};
use crate::model::Type;

fn string(value: &str) -> String {
    // JSON permits these literal characters; TypeScript counts them as source line breaks.
    serde_json::to_string(value).expect("JSON string").replace('\u{2028}', "\\u2028").replace('\u{2029}', "\\u2029")
}
fn ty(value: &Type) -> String {
    match value {
        Type::Int => "bigint".into(), Type::Bool => "boolean".into(), Type::Text => "string".into(),
        Type::Sequence(item) => format!("ReadonlyArray<{}>", ty(item)),
        Type::Record(fields) => format!("{{ {} }}", fields.iter().map(|(name, value)| format!("readonly [{}]: {}", string(name), ty(value))).collect::<Vec<_>>().join("; ")),
    }
}

struct Printer<'a> { names: &'a BTreeMap<String, String> }
impl Printer<'_> {
    fn term(&self, value: &Term) -> String {
        match &value.kind {
            TermKind::Int(value) => format!("BigInt({})", string(value)),
            TermKind::Bool(value) => value.to_string(), TermKind::Text(value) => string(value),
            TermKind::Variable(name) => format!("v_{name}"),
            TermKind::Definition(name) => self.names[name].clone(),
            TermKind::Record(fields) => format!("Object.freeze({{ {} }})", fields.iter().map(|(name, value)| format!("[{}]: {}", string(name), self.term(value))).collect::<Vec<_>>().join(", ")),
            TermKind::Sequence(items) => format!("Object.freeze([{}])", items.iter().map(|x| self.term(x)).collect::<Vec<_>>().join(", ")),
            TermKind::Field(record, name) => format!("({})[{}]", self.term(record), string(name)),
            TermKind::Call(name, arguments) => format!("{}({})", self.names[name], arguments.iter().map(|x| self.term(x)).collect::<Vec<_>>().join(", ")),
            TermKind::Primitive(primitive, arguments) => {
                let args: Vec<_> = arguments.iter().map(|x| self.term(x)).collect();
                match primitive {
                    Primitive::IntCompare => format!("compare({}, {})", args[0], args[1]),
                    Primitive::BoolNot => format!("(!{})", args[0]),
                    other => {
                        let op = match other { Primitive::IntEq => "===", Primitive::IntAdd => "+", Primitive::IntSub => "-", Primitive::IntMul => "*", _ => unreachable!() };
                        format!("({} {op} {})", args[0], args[1])
                    }
                }
            }
            TermKind::If(condition, yes, no) => format!("({} ? {} : {})", self.term(condition), self.term(yes), self.term(no)),
            // One evaluation of the scrutinee, and only the selected branch is evaluated.
            TermKind::Match(value, branches) => format!("((ordering: Ordering) => {{ switch (ordering) {{ case 'Less': return {}; case 'Equal': return {}; case 'Greater': return {}; }} }})({})", self.term(&branches["Less"]), self.term(&branches["Equal"]), self.term(&branches["Greater"]), self.term(value)),
        }
    }
    fn plan(&self, plan: &OrderedPlan) -> String {
        match plan {
            OrderedPlan::Scan { source, .. } => self.names[source].clone(),
            // Each source completes before its filter; do not fuse nested filters.
            OrderedPlan::Filter { source, predicate, .. } => format!("Object.freeze(({}).filter((row) => {}(row)))", self.plan(source), self.names[predicate]),
        }
    }
}

pub fn emit(program: &Program, revision: &str) -> (Vec<Artifact>, Vec<SourceMapping>) {
    let names: BTreeMap<_, _> = program.definitions.keys().enumerate().map(|(index, name)| (name.clone(), format!("d{index}"))).collect();
    let printer = Printer { names: &names };
    let mut lines = vec![
        "// Generated by Gift. Edit the author module; this file is a rebuildable artifact.".to_owned(),
        "type Ordering = 'Less' | 'Equal' | 'Greater';".to_owned(),
        "function compare(a: bigint, b: bigint): Ordering { return a < b ? 'Less' : a > b ? 'Greater' : 'Equal'; }".to_owned(),
    ];
    let mut mappings = Vec::new();
    for id in &program.order {
        let name = &names[id];
        let declaration = match &program.definitions[id] {
            LoweredDefinition::Type(value) => format!("type {name} = {};", ty(value)),
            LoweredDefinition::Constant { ty: value_type, value } => format!("const {name}: {} = {};", ty(value_type), printer.term(value)),
            LoweredDefinition::Function { parameters, returns, body } => format!("function {name}({}): {} {{ return {}; }}", parameters.iter().map(|p| format!("v_{}: {}", p.name, ty(&p.ty))).collect::<Vec<_>>().join(", "), ty(returns), printer.term(body)),
            LoweredDefinition::Meaning { parameters, returns, interpretation } => format!("function {name}({}): {} {{ return {}({}); }}", parameters.iter().map(|p| format!("v_{}: {}", p.name, ty(&p.ty))).collect::<Vec<_>>().join(", "), ty(returns), names[interpretation], parameters.iter().map(|p| format!("v_{}", p.name)).collect::<Vec<_>>().join(", ")),
            LoweredDefinition::Query { result, plan } => format!("const {name}: {} = {};", ty(result), printer.plan(plan)),
        };
        lines.push(declaration);
        mappings.push(SourceMapping { definition: id.clone(), source_pointer: format!("/definitions/{id}"), source_revision: revision.to_owned(), artifact: "src/index.ts".to_owned(), start_line: lines.len(), end_line: lines.len() });
    }
    for (public, id) in &program.exports {
        let type_only = if matches!(program.definitions[id], LoweredDefinition::Type(_)) { "type " } else { "" };
        lines.push(format!("export {type_only}{{ {} as {public} }};", names[id]));
    }
    // Keep an empty-export module valid as well.
    lines.push("export {};".to_owned());
    let artifacts = vec![
        Artifact { path: "src/index.ts".into(), content: format!("{}\n", lines.join("\n")) },
        Artifact { path: "src/main.ts".into(), content: "import * as values from './index.js';\n// Exact Int values use decimal strings in this demonstration's JSON observation.\nconsole.log(JSON.stringify(values, (_key, value: unknown) => typeof value === 'bigint' ? value.toString() : value));\n".into() },
        Artifact { path: "package.json".into(), content: "{\n  \"name\": \"gift-generated\",\n  \"version\": \"0.0.0\",\n  \"private\": true,\n  \"type\": \"module\",\n  \"exports\": \"./dist/index.js\",\n  \"scripts\": { \"build\": \"tsc -p tsconfig.json\", \"start\": \"node dist/main.js\" },\n  \"devDependencies\": { \"typescript\": \"6.0.3\" }\n}\n".into() },
        Artifact { path: "tsconfig.json".into(), content: "{\n  \"compilerOptions\": { \"target\": \"ES2020\", \"module\": \"NodeNext\", \"strict\": true, \"declaration\": true, \"outDir\": \"dist\", \"rootDir\": \"src\", \"types\": [] },\n  \"include\": [\"src/**/*.ts\"]\n}\n".into() },
    ];
    (artifacts, mappings)
}
